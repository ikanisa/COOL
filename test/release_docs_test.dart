  Map<File, File> hideAndroidReleaseArtifactsForTest() {
    final artifacts = <File>[
      File('build/app/outputs/flutter-apk/app-production-release.apk'),
      File(
        'build/app/outputs/bundle/productionRelease/app-production-release.aab',
      ),
    ];
    final hiddenArtifacts = <File, File>{};
    final backupDir = Directory('.cache/release_docs_hidden_artifacts')
      ..createSync(recursive: true);
    for (final artifact in artifacts) {
      if (!artifact.existsSync()) continue;
      final backup = File(
        '${backupDir.path}/${artifact.path.replaceAll('/', '__')}',
      );
      if (backup.existsSync()) {
        backup.deleteSync();
      }
      artifact.renameSync(backup.path);
      hiddenArtifacts[artifact] = backup;
    }
    return hiddenArtifacts;
  }

  void restoreAndroidReleaseArtifacts(Map<File, File> hiddenArtifacts) {
    for (final entry in hiddenArtifacts.entries) {
      final artifact = entry.key;
      final backup = entry.value;
      artifact.parent.createSync(recursive: true);
      if (backup.existsSync()) {
        backup.renameSync(artifact.path);
      }
    }
  }

  ({File evidence, File sidecar}) writeBinaryUatEvidence(
    Directory dir, {
    required String reviewedBy,
    required String reviewedAt,
  }) {
    final evidence = File('${dir.path}/UAT-01.bin')
      ..writeAsBytesSync(<int>[1, 2, 3, 4, 5, 6]);
    final sha = Process.runSync('shasum', [
      '-a',
      '256',
      evidence.path,
    ]).stdout.toString().split(RegExp(r'\s+')).first;
    final sidecar = File('${evidence.path}.sanitized.json')
      ..writeAsStringSync(
        jsonEncode(<String, dynamic>{
          'sanitized': true,
          'contains_production_data': false,
          'reviewed_by': reviewedBy,
          'reviewed_at': reviewedAt,
          'sha256': sha,
        }),
      );
    return (evidence: evidence, sidecar: sidecar);
  }


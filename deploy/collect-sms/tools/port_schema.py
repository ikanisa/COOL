#!/usr/bin/env python3
"""Deterministic SQL port of the retained OpenSMS v0.3 migrations.

The source migrations are immutable inputs. The generated PostgreSQL migration
retains every table, index, view and trigger, with explicit SQLite compatibility
functions. Review both generated SQL and adapter tests when changing this port.
"""
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT.parents[1] / 'supabase/migrations/20261101012503_collect_sms_gateway.sql'

HEADER = '''-- OpenSMS v0.3, archive fbb65c024d8b1c1340245ea0014d525f7b1e2009910598e34de56c2ca0eb4909.
-- Generated by deploy/collect-sms/tools/port_schema.py. No provider activation.
BEGIN;
DO $$BEGIN
 IF NOT EXISTS(SELECT 1 FROM pg_roles WHERE rolname='collect_sms_runtime') THEN
  CREATE ROLE collect_sms_runtime NOLOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOINHERIT NOREPLICATION NOBYPASSRLS;
 END IF;
END$$;
CREATE SCHEMA collect_sms;
REVOKE ALL ON SCHEMA collect_sms FROM PUBLIC,anon,authenticated,service_role;
GRANT USAGE ON SCHEMA collect_sms TO collect_sms_runtime;
SET LOCAL search_path=collect_sms,pg_catalog;
CREATE FUNCTION json_valid(input text) RETURNS boolean LANGUAGE plpgsql IMMUTABLE AS $$
BEGIN PERFORM input::jsonb; RETURN true; EXCEPTION WHEN OTHERS THEN RETURN false; END$$;
CREATE FUNCTION json_extract(input text,path text) RETURNS text LANGUAGE sql IMMUTABLE AS $$
 SELECT input::jsonb #>> string_to_array(substr(path,3),'.') $$;
CREATE FUNCTION json_each(input text) RETURNS TABLE(value text) LANGUAGE sql IMMUTABLE AS $$
 SELECT CASE WHEN jsonb_typeof(item)='string' THEN item #>> '{}' ELSE item::text END
 FROM jsonb_array_elements(input::jsonb) AS item $$;
CREATE FUNCTION max(a bigint,b bigint) RETURNS bigint LANGUAGE sql IMMUTABLE AS $$SELECT greatest(a,b)$$;
'''

def expressions(sql):
    sql = re.sub(r'\bINTEGER\b', 'bigint', sql, flags=re.I)
    sql = re.sub(r'NEW\.(\w+) IS NOT OLD\.(\w+)', r'NEW.\1 IS DISTINCT FROM OLD.\2', sql)
    sql = sql.replace("lower(hex(randomblob(16)))", "replace(gen_random_uuid()::text,'-','')")
    # json_object has only flat scalar fields in these three webhook triggers.
    sql = re.sub(r'json_object\(([^\n]+?)\)(?=,\n|,NEW\.)', r'jsonb_build_object(\1)::text', sql)
    sql = re.sub(r"strftime\('%Y-%m-%dT%H:%M:%fZ',NEW.created_at,'-(\d+) (minutes?)'\)",
        lambda m: "to_char((NEW.created_at::timestamptz-interval '"+m[1]+" minutes') AT TIME ZONE 'UTC','YYYY-MM-DD\"T\"HH24:MI:SS.MS\"Z\"')", sql)
    return sql

def main():
    tables, triggers, sources = [], {}, []
    for source in sorted((ROOT/'upstream/migrations').glob('*.sql')):
        raw=source.read_text()
        tables += re.findall(r'CREATE TABLE\s+(\w+)',raw,re.I)
        raw=re.sub(r'PRAGMA foreign_keys = ON;\s*','',raw)
        pattern=r'CREATE TRIGGER (\w+) (BEFORE|AFTER) (INSERT|UPDATE(?: OF \w+)?|DELETE) ON (\w+)\s*(?:WHEN (.*?))?\s*BEGIN\s*(.*?)\s*END;'
        def trigger(m):
            name,timing,event,table,condition,body=m.groups();triggers[name]=table
            def abort(a):
                code,where=a.groups()
                statement="RAISE EXCEPTION '%s' USING ERRCODE='23514';"%code
                return ('IF '+where+' THEN '+statement+' END IF;') if where else statement
            body=re.sub(r"SELECT RAISE\(ABORT,'([^']+)'\)(?: WHERE (.*?))?;",abort,body,flags=re.S)
            if condition: body='IF '+condition+' THEN\n'+body+'\nEND IF;'
            return f'''CREATE OR REPLACE FUNCTION trigger_{name}() RETURNS trigger LANGUAGE plpgsql
 SET search_path=collect_sms,pg_catalog AS $gateway_trigger$
BEGIN
{body}
RETURN NEW;
END$gateway_trigger$;
CREATE TRIGGER {name} {timing} {event} ON {table} FOR EACH ROW EXECUTE FUNCTION trigger_{name}();
ALTER TABLE {table} ENABLE ALWAYS TRIGGER {name};'''
        raw=re.sub(pattern,trigger,raw,flags=re.S)
        raw=re.sub(r'DROP TRIGGER (\w+);',lambda m:f'DROP TRIGGER {m[1]} ON {triggers[m[1]]};',raw)
        if 'RAISE(ABORT' in raw or 'BEGIN SELECT' in raw: raise ValueError('Unconverted trigger '+str(source))
        sources.append('-- Source: '+source.name+'\n'+expressions(raw))
    tail='''
-- Every mutation, including a direct internal SQL caller, uses the same lock.
-- Adapter batches acquire this before their first read, preserving D1's serial
-- writer ordering for OTP limits, device assignment and segment budgets.
CREATE FUNCTION serialize_gateway_write() RETURNS trigger LANGUAGE plpgsql
 SET search_path=pg_catalog AS $$BEGIN PERFORM pg_advisory_xact_lock(721340019927::bigint); RETURN NULL; END$$;
'''
    for table in tables:
        tail+=f'''ALTER TABLE {table} ENABLE ROW LEVEL SECURITY;
ALTER TABLE {table} FORCE ROW LEVEL SECURITY;
CREATE POLICY internal_gateway ON {table} TO collect_sms_runtime USING(true) WITH CHECK(true);
CREATE TRIGGER gateway_writer BEFORE INSERT OR UPDATE OR DELETE ON {table} FOR EACH STATEMENT EXECUTE FUNCTION serialize_gateway_write();
ALTER TABLE {table} ENABLE ALWAYS TRIGGER gateway_writer;
'''
    tail+='''ALTER VIEW attempt_evidence SET (security_invoker=true);
REVOKE ALL ON ALL TABLES IN SCHEMA collect_sms FROM PUBLIC,anon,authenticated,service_role;
REVOKE ALL ON ALL FUNCTIONS IN SCHEMA collect_sms FROM PUBLIC,anon,authenticated,service_role;
GRANT SELECT,INSERT,UPDATE,DELETE ON ALL TABLES IN SCHEMA collect_sms TO collect_sms_runtime;
GRANT EXECUTE ON ALL FUNCTIONS IN SCHEMA collect_sms TO collect_sms_runtime;
ALTER DEFAULT PRIVILEGES IN SCHEMA collect_sms REVOKE EXECUTE ON FUNCTIONS FROM PUBLIC;
COMMENT ON SCHEMA collect_sms IS 'Private OpenSMS gateway copies: blocked personal erasure until exact subject selector reviewed. Include in encrypted backups and restore verification.';
COMMIT;
'''
    OUT.write_text(HEADER+'\n'.join(sources)+tail)
    print(f'Generated {len(tables)} tables and {len(triggers)} retained trigger definitions.')

if __name__=='__main__': main()

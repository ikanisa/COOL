// Generates Dart metadata only. It does not read, encode or replace images.
import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const dart = value => typeof value === 'string'
  ? "'" + value.replaceAll('\\', '\\\\').replaceAll("'", "\\'").replaceAll('$', '\\$') + "'"
  : Array.isArray(value) ? '[' + value.map(dart).join(', ') + ']' : String(value);
const symbol = id => '_cover' + id.split('-').map(word => word[0].toUpperCase() + word.slice(1)).join('');
const header = "// Generated by scripts/assets/group_cover_catalog_source.mjs.\npart of 'collect_group_cover.dart';\n\n";

export function renderGroupCoverCatalog(catalog) {
  const families = new Map(catalog.families.map(family => [family.id, family]));
  const definitions = new Map();
  const order = [];
  const seen = new Set();
  for (const a of catalog.assets) {
    if (!/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(a.id) || !/^[a-z][a-z0-9_]*$/.test(a.family)) {
      throw new Error('Cover identifiers must be safe Dart/file identifiers');
    }
    const variable = symbol(a.id);
    if (seen.has(variable)) throw new Error(`Duplicate generated cover identifier: ${a.id}`);
    seen.add(variable);
    const family = families.get(a.family);
    if (!family) throw new Error(`Unknown cover family: ${a.family}`);
    const terms = [...Object.values(a.labels), ...Object.values(family.labels), ...a.search_terms];
    const definition = `const ${variable} = CollectGroupCover(\n  id: ${dart(a.id)}, version: ${a.version}, name: ${dart(a.labels.en)},\n  family: ${dart(a.family)}, theme: ${dart(a.theme)},\n  types: ${dart(a.collection_types)}, terms: ${dart(terms)},\n  context: ${dart(a.explicit_context)}, namedGroup: ${dart(a.named_group ?? null)},\n  generalDefault: ${a.general_default}, priority: ${a.editorial_priority},\n  focalX: ${Number(a.focal_point.x).toFixed(2)}, focalY: ${Number(a.focal_point.y).toFixed(2)},\n);\n`;
    if (!definitions.has(a.family)) definitions.set(a.family, []);
    definitions.get(a.family).push(definition);
    order.push(variable);
  }
  if (!order.length) throw new Error('Cover catalog must not be empty');
  const files = new Map([
    ['collect_group_cover_catalog.dart', header + `const collectGroupCovers = <CollectGroupCover>[\n${order.map(name => `  ${name},`).join('\n')}\n];\n`],
    ...[...definitions].map(([family, entries]) => [`collect_group_cover_catalog_${family}.dart`, header + entries.join('\n')]),
  ]);
  return files;
}

export async function writeGroupCoverCatalog(root, catalog) {
  const files = renderGroupCoverCatalog(catalog);
  const directory = path.join(root, 'lib/shared/models');
  const ownerPath = path.join(directory, 'collect_group_cover.dart');
  const owner = await fs.readFile(ownerPath, 'utf8');
  const parts = '// BEGIN GENERATED COVER PARTS\n' + [...files.keys()].map(file => `part '${file}';`).join('\n') + '\n// END GENERATED COVER PARTS';
  const region = /\/\/ BEGIN GENERATED COVER PARTS\n[\s\S]*?\/\/ END GENERATED COVER PARTS/;
  const legacy = "part 'collect_group_cover_catalog.dart';";
  if (!region.test(owner) && !owner.includes(legacy)) throw new Error('Missing owned catalog part declaration');
  const updatedOwner = region.test(owner) ? owner.replace(region, parts) : owner.replace(legacy, parts);
  for (const [file, contents] of files) await fs.writeFile(path.join(directory, file), contents);
  await fs.writeFile(ownerPath, updatedOwner);
  return [...files.keys()];
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
  const catalog = JSON.parse(await fs.readFile(path.join(root, 'assets/group_covers/rwanda/catalog.v1.json')));
  console.log(JSON.stringify({ generated: await writeGroupCoverCatalog(root, catalog), images_changed: false }));
}

"""Translate the SQL forms used by the reviewed SQLite schema snapshot."""

import re

TOKEN = re.compile(
    r"--[^\n]*|/\*[\s\S]*?\*/|'(?:''|[^'])*'|\"(?:\"\"|[^\"])*\"|"
    r"[A-Za-z_][A-Za-z_0-9]*|\d+(?:\.\d+)?|!=|<>|<=|>=|\|\||[^\s]"
)
NUMBER = re.compile(r"\d+(?:\.\d+)?")
COMPARISONS = {"=", "!=", "<>", "<", "<=", ">", ">="}
POSTGRES_REPLACEMENTS = [
    (r"\bWHERE 1\b", "WHERE true", re.I),
    (r"\bCOLLATE NOCASE\b", "", re.I),
    (r"\bCOLLATE BINARY\b", 'COLLATE "C"', re.I),
    (r"\bINSERT OR IGNORE INTO\b", "INSERT INTO", re.I),
    (r"\bBIGINT PRIMARY KEY AUTOINCREMENT\b", "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY", re.I),
    (r"\bused = used \+ 1\b", "used = auth_rate_buckets.used + 1", 0),
]
TRIGGER_HEADER = re.compile(
    r"CREATE TRIGGER\s+(\w+)\s+(BEFORE|AFTER)\s+"
    r"(INSERT|DELETE|UPDATE(?:\s+OF\s+.+?)?)\s+ON\s+(\w+)"
    r"(?:\s+WHEN\s+([\s\S]+))?\s*$",
    re.I | re.S,
)
CASE_RAISE = re.compile(
    r"SELECT\s*\(?\s*CASE WHEN ([\s\S]+) THEN RAISE\s*\(\s*(ABORT|IGNORE)\s*"
    r"(?:,\s*('(?:''|[^'])*'))?\s*\)\s*END\s*\)?",
    re.I,
)
DIRECT_RAISE = re.compile(r"SELECT RAISE\s*\(\s*ABORT\s*,\s*('(?:''|[^'])*')\s*\)", re.I)


def tokenize(sql):
    return [token for token in TOKEN.findall(sql) if not token.startswith(("--", "/*"))]


def matching_parenthesis(tokens, start, direction=1):
    opening, closing = ("(", ")") if direction == 1 else (")", "(")
    end = len(tokens) if direction == 1 else -1
    depth = 0
    for index in range(start, end, direction):
        if tokens[index] == opening:
            depth += 1
        elif tokens[index] == closing:
            depth -= 1
            if depth == 0:
                return index
    raise ValueError("Unbalanced SQL expression")


def glob_regex(literal):
    pattern = literal[1:-1].replace("''", "'")
    converted = ["^"]
    index = 0
    while index < len(pattern):
        character = pattern[index]
        if character == "*":
            converted.append(".*")
        elif character == "?":
            converted.append(".")
        elif character == "[":
            ending = pattern.find("]", index + 1)
            if ending < 0:
                converted.append(r"\[")
            else:
                converted.append(pattern[index:ending + 1])
                index = ending
        else:
            converted.append(re.escape(character))
        index += 1
    converted.append("$")
    return "'" + "".join(converted).replace("'", "''") + "'"


def rewrite_glob(tokens, operator):
    end = operator - 1
    negated = tokens[end].upper() == "NOT"
    if negated:
        end -= 1
    start = end
    if tokens[end] == ")":
        start = matching_parenthesis(tokens, end, -1)
        if start > 0 and re.match(r"^[A-Za-z_]", tokens[start - 1]):
            start -= 1
    while start >= 2 and tokens[start - 1] == ".":
        start -= 2
    pattern = tokens[operator + 1]
    if not pattern.startswith("'"):
        raise ValueError("Unreviewed dynamic GLOB")
    comparison = "!~" if negated else "~"
    tokens[start:operator + 2] = ["(", *tokens[start:end + 1], comparison, glob_regex(pattern), ")"]
    return start


def has_multiple_arguments(tokens, start, end):
    depth = 0
    for token in tokens[start:end]:
        if token == "(":
            depth += 1
        elif token == ")":
            depth -= 1
        elif token == "," and depth == 0:
            return True
    return False


def translate_sql(sql):
    tokens = tokenize(sql)
    index = 0
    while index < len(tokens):
        keyword = tokens[index].upper()
        following = tokens[index + 1] if index + 1 < len(tokens) else None
        if keyword == "GLOB":
            index = rewrite_glob(tokens, index)
        elif keyword == "IS" and following is not None:
            negated = following.upper() == "NOT"
            operand = index + (2 if negated else 1)
            if tokens[operand].upper() not in {"NULL", "TRUE", "FALSE", "DISTINCT"}:
                tokens[index:operand] = ["IS", "DISTINCT", "FROM"] if negated else ["IS", "NOT", "DISTINCT", "FROM"]
        elif keyword in {"MAX", "MIN", "JSON_EXTRACT"} and following == "(":
            end = matching_parenthesis(tokens, index + 1)
            if keyword == "JSON_EXTRACT":
                if end + 2 < len(tokens) and tokens[end + 1] in COMPARISONS and NUMBER.fullmatch(tokens[end + 2]):
                    # SQLite number and boolean values differ from numeric strings.
                    tokens[index] = "json_numeric"
            elif has_multiple_arguments(tokens, index + 2, end):
                tokens[index] = "greatest" if keyword == "MAX" else "least"
        elif keyword == "INTEGER":
            tokens[index] = "BIGINT"
        elif keyword == "STRICT":
            tokens[index] = ""
        index += 1

    converted = " ".join(token for token in tokens if token)
    for pattern, replacement, flags in POSTGRES_REPLACEMENTS:
        converted = re.sub(pattern, replacement, converted, flags=flags)
    return converted


def split_trigger_statements(body):
    current = []
    for token in tokenize(body):
        if token == ";":
            if current:
                yield " ".join(current)
                current.clear()
        else:
            current.append(token)
    if current:
        yield " ".join(current)


def raise_exception(message):
    return f"RAISE EXCEPTION USING ERRCODE='P0001', MESSAGE={message};"


def translate_trigger_statement(statement, trigger_name):
    conditional = CASE_RAISE.fullmatch(statement)
    if conditional:
        condition, mode, message = conditional.groups()
        action = "RETURN NULL;" if mode.upper() == "IGNORE" else raise_exception(message)
        return f"IF {translate_sql(condition)} THEN {action} END IF;"

    direct = DIRECT_RAISE.fullmatch(statement)
    if direct:
        return raise_exception(direct.group(1))

    converted = translate_sql(statement)
    if re.match(r"INSERT OR IGNORE", statement, re.I):
        converted += " ON CONFLICT DO NOTHING"
    if "RAISE (" in converted.upper():
        raise ValueError("Untranslated RAISE in " + trigger_name)
    return converted + ";"


def translate_trigger(sql):
    header, body = re.split(r"\bBEGIN\b", sql, maxsplit=1, flags=re.I)
    body = re.sub(r"\bEND\s*$", "", body, flags=re.I)
    match = TRIGGER_HEADER.match(header.strip())
    if not match:
        raise ValueError("Unreviewed trigger header: " + header)
    name, timing, event, table, condition = match.groups()
    returning = "OLD" if event.upper() == "DELETE" else "NEW"
    statements = []
    if condition:
        statements.append(f"IF NOT coalesce(({translate_sql(condition)}), false) THEN RETURN {returning}; END IF;")
    statements.extend(translate_trigger_statement(statement, name) for statement in split_trigger_statements(body))
    function_body = "\n  ".join(statements)
    return (
        f"CREATE FUNCTION private.trg_{name}() RETURNS trigger LANGUAGE plpgsql SET search_path=app,pg_catalog AS $trigger$\n"
        f"BEGIN\n  {function_body}\n  RETURN {returning};\nEND;\n$trigger$;\n"
        f"CREATE TRIGGER {name} {timing} {event} ON app.{table} FOR EACH ROW EXECUTE FUNCTION private.trg_{name}();\n"
    )

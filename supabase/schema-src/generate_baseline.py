#!/usr/bin/env python3
"""Curate the final Cloudflare17 schema into PostgreSQL17.

Reads only the immutable ordered SQL input bodies; does not connect to a provider.
The generated SQL preserves source names and shapes for the domain adapter. Its
translation report is evidence, not proof of semantic equivalence.
"""
import hashlib
import argparse
import json
from pathlib import Path
import re
import sqlite3

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
TOKEN = re.compile(r"--[^\n]*|/\*[\s\S]*?\*/|'(?:''|[^'])*'|\"(?:\"\"|[^\"])*\"|[A-Za-z_][A-Za-z_0-9]*|\d+(?:\.\d+)?|!=|<>|<=|>=|\|\||[^\s]", re.M)


def tokens(sql):
    return [t for t in TOKEN.findall(sql) if not t.startswith(('--', '/*'))]


def matching(ts, start, direction=1):
    depth = 0
    for i in range(start, len(ts) if direction == 1 else -1, direction):
        if ts[i] == ('(' if direction == 1 else ')'): depth += 1
        elif ts[i] == (')' if direction == 1 else '('):
            depth -= 1
            if depth == 0: return i
    raise ValueError('Unbalanced SQL expression')


def glob_regex(pattern):
    p = pattern[1:-1].replace("''", "'")
    out, i = '^', 0
    while i < len(p):
        ch = p[i]
        if ch == '*': out += '.*'
        elif ch == '?': out += '.'
        elif ch == '[':
            j = p.find(']', i + 1)
            if j < 0: out += r'\['
            else: out += p[i:j + 1]; i = j
        else: out += re.escape(ch)
        i += 1
    return "'" + (out + '$').replace("'", "''") + "'"


def transform(sql):
    ts = tokens(sql)
    i = 0
    while i < len(ts):
        upper = ts[i].upper()
        if upper == 'GLOB':
            end = i - 1
            neg = ts[end].upper() == 'NOT'
            if neg: end -= 1
            start = end
            if ts[end] == ')':
                start = matching(ts, end, -1)
                if start > 0 and re.match(r'^[A-Za-z_]', ts[start - 1]): start -= 1
            while start >= 2 and ts[start - 1] == '.': start -= 2
            if not ts[i + 1].startswith("'"): raise ValueError('Unreviewed dynamic GLOB')
            ts[start:i + 2] = ['('] + ts[start:end + 1] + ['!~' if neg else '~', glob_regex(ts[i + 1]), ')']
            i = start + 1
            continue
        if upper == 'IS' and i + 1 < len(ts):
            j = i + 1
            neg = ts[j].upper() == 'NOT'
            if neg: j += 1
            if ts[j].upper() not in ('NULL', 'TRUE', 'FALSE', 'DISTINCT'):
                ts[i:j] = ['IS', 'DISTINCT', 'FROM'] if neg else ['IS', 'NOT', 'DISTINCT', 'FROM']
        if upper in ('MAX', 'MIN') and i + 1 < len(ts) and ts[i + 1] == '(':
            end = matching(ts, i + 1)
            depth, commas = 0, 0
            for t in ts[i + 2:end]:
                if t == '(': depth += 1
                elif t == ')': depth -= 1
                elif t == ',' and depth == 0: commas += 1
            if commas: ts[i] = 'greatest' if upper == 'MAX' else 'least'
        if upper == 'JSON_EXTRACT' and i + 1 < len(ts) and ts[i + 1] == '(':
            end = matching(ts, i + 1)
            if end + 2 < len(ts) and ts[end + 1] in ('=', '!=', '<>', '<', '<=', '>', '>=') and re.fullmatch(r'\d+(?:\.\d+)?', ts[end + 2]):
                # SQLite numbers/booleans and numeric-looking JSON strings are
                # different values. A TEXT conversion must not authorize '1'.
                ts[i] = 'json_numeric'
        if upper == 'INTEGER': ts[i] = 'BIGINT'
        if upper == 'STRICT': ts[i] = ''
        i += 1
    value = ' '.join(t for t in ts if t)
    value = re.sub(r'\bWHERE 1\b', 'WHERE true', value, flags=re.I)
    value = re.sub(r'\bCOLLATE NOCASE\b', '', value, flags=re.I)
    value = re.sub(r'\bCOLLATE BINARY\b', 'COLLATE "C"', value, flags=re.I)
    value = re.sub(r'\bINSERT OR IGNORE INTO\b', 'INSERT INTO', value, flags=re.I)
    value = re.sub(r'\bBIGINT PRIMARY KEY AUTOINCREMENT\b', 'BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY', value, flags=re.I)
    value = re.sub(r'\bused = used \+ 1\b', 'used = auth_rate_buckets.used + 1', value)
    return value


def split_statements(body):
    ts = tokens(body)
    pieces, current = [], []
    for t in ts:
        if t == ';':
            if current: pieces.append(' '.join(current)); current = []
        else: current.append(t)
    if current: pieces.append(' '.join(current))
    return pieces


def trigger_sql(row):
    raw = row['sql']
    header, body = re.split(r'\bBEGIN\b', raw, maxsplit=1, flags=re.I)
    body = re.sub(r'\bEND\s*$', '', body, flags=re.I)
    m = re.match(r'CREATE TRIGGER\s+(\w+)\s+(BEFORE|AFTER)\s+(INSERT|DELETE|UPDATE(?:\s+OF\s+.+?)?)\s+ON\s+(\w+)(?:\s+WHEN\s+([\s\S]+))?\s*$', header.strip(), re.I | re.S)
    if not m: raise ValueError('Unreviewed trigger header: ' + header)
    name, timing, event, table, when = m.groups()
    returning = 'OLD' if event.upper() == 'DELETE' else 'NEW'
    lines = []
    if when: lines.append('IF NOT coalesce((' + transform(when) + '), false) THEN RETURN ' + returning + '; END IF;')
    for stmt in split_statements(body):
        case = re.fullmatch(r"SELECT\s*\(?\s*CASE WHEN ([\s\S]+) THEN RAISE\s*\(\s*(ABORT|IGNORE)\s*(?:,\s*('(?:''|[^'])*'))?\s*\)\s*END\s*\)?", stmt, re.I)
        direct = re.fullmatch(r"SELECT RAISE\s*\(\s*ABORT\s*,\s*('(?:''|[^'])*')\s*\)", stmt, re.I)
        if case:
            condition, mode, message = case.groups()
            action = 'RETURN NULL;' if mode.upper() == 'IGNORE' else "RAISE EXCEPTION USING ERRCODE='P0001', MESSAGE=" + message + ';'
            lines.append('IF ' + transform(condition) + ' THEN ' + action + ' END IF;')
        elif direct: lines.append("RAISE EXCEPTION USING ERRCODE='P0001', MESSAGE=" + direct.group(1) + ';')
        else:
            converted = transform(stmt)
            if re.match(r'INSERT OR IGNORE', stmt, re.I): converted += ' ON CONFLICT DO NOTHING'
            if 'RAISE (' in converted.upper(): raise ValueError('Untranslated RAISE in ' + name)
            lines.append(converted + ';')
    sql = f"CREATE FUNCTION private.trg_{name}() RETURNS trigger LANGUAGE plpgsql SET search_path=app,pg_catalog AS $trigger$\nBEGIN\n  " + '\n  '.join(lines) + f'\n  RETURN {returning};\nEND;\n$trigger$;\n'
    sql += f'CREATE TRIGGER {name} {timing} {event} ON app.{table} FOR EACH ROW EXECUTE FUNCTION private.trg_{name}();\n'
    return sql


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='Verify generated SQL/source manifest byte equality without writing')
    args = parser.parse_args()
    # New source contracts use additive migrations, never rewritten historical
    # baseline bytes. Keep their exact source/chain identity in the same gate.
    additions = [('client-diagnostics.sql', '20261029120000_collect_client_diagnostics.sql'),
                 ('notification-delivery.sql', '20261029130000_collect_notification_delivery.sql')]
    for source_name, migration_name in additions:
        source = (HERE / source_name).read_text()
        migration = ROOT / 'supabase/migrations' / migration_name
        if args.check:
            if not migration.is_file() or migration.read_text() != source:
                raise SystemExit('Additive source drift: ' + source_name)
        else:
            migration.write_text(source)
    # An additive migration must carry the exact current curated definition;
    # preserving the old generated baseline must not hide source/chain drift.
    storage = (HERE / 'storage.sql').read_text()
    correction = (ROOT / 'supabase/migrations/20261020174856_collect_retention_retry_authority.sql').read_text()
    definition = r'CREATE (?:OR REPLACE )?FUNCTION private\.assert_storage_delete_authorized\(p_key text\)[\s\S]*?END\$\$;'
    current = re.findall(definition, storage)
    migrated = re.findall(definition, correction)
    normalize = lambda body: body.replace('CREATE OR REPLACE FUNCTION ', 'CREATE FUNCTION ', 1)
    if len(current) != 1 or len(migrated) != 1 or normalize(current[0]) != normalize(migrated[0]):
        raise SystemExit('Current Storage definition differs from its additive migration')
    db = sqlite3.connect(':memory:')
    inputs = []
    for p in sorted((ROOT / 'deploy/platform-api/migrations').glob('[0-9]*.sql')):
        body = p.read_bytes()
        inputs.append({'path': str(p.relative_to(ROOT)), 'sha256': hashlib.sha256(body).hexdigest()})
        db.executescript(body.decode())
    objects = [dict(zip(('type', 'name', 'table', 'sql'), r)) for r in db.execute("SELECT type,name,tbl_name,sql FROM sqlite_master WHERE sql IS NOT NULL AND name NOT LIKE 'sqlite_%' ORDER BY rowid")]
    counts = {k: sum(o['type'] == k for o in objects) for k in ('table', 'index', 'trigger', 'view')}
    if counts != {'table': 97, 'index': 34, 'trigger': 169, 'view': 2}: raise ValueError('Source inventory changed: ' + repr(counts))
    pieces = ["-- Generated from the exact source bodies in source_manifest.json. Do not hand-edit.\nBEGIN;\nCREATE SCHEMA IF NOT EXISTS app;\nCREATE SCHEMA IF NOT EXISTS private;\nCREATE SCHEMA IF NOT EXISTS api;\nREVOKE ALL ON SCHEMA app,private,api FROM PUBLIC;\nSET LOCAL search_path=app,pg_catalog;\n", (HERE / 'compatibility.sql').read_text()]
    fks = []
    for o in objects:
        if o['type'] != 'table': continue
        raw = o['sql']
        # Create all relations before their foreign keys: the source includes
        # legitimate session/factor and privacy-head/claim cycles.
        raw = re.sub(r'\bREFERENCES\s+(\w+)\s*\((\w+)\)', '', raw, flags=re.I)
        pieces.append(transform(raw) + ';\n')
        for fk in db.execute('PRAGMA foreign_key_list("' + o['name'] + '")'):
            fid, seq, target, col, target_col, update, delete, match = fk
            if seq != 0: raise ValueError('Composite FK requires review')
            fks.append(f'ALTER TABLE app.{o["name"]} ADD CONSTRAINT fk_{o["name"]}_{fid} FOREIGN KEY ({col}) REFERENCES app.{target}({target_col}) ON UPDATE {update} ON DELETE {delete} DEFERRABLE INITIALLY IMMEDIATE;\n')
    pieces += fks
    # The only populated source-migration table is the reviewed role/capability
    # definition catalog. It is not a grant to any current or future user.
    for table, in db.execute("SELECT name FROM sqlite_master WHERE type='table' AND name NOT LIKE 'sqlite_%'").fetchall():
        rows = db.execute('SELECT * FROM "' + table + '"').fetchall()
        if not rows: continue
        if table != 'admin_account_role_capabilities': raise ValueError('Unreviewed source seed table: ' + table)
        for role, permission in rows:
            quote = lambda value: "'" + value.replace("'", "''") + "'"
            pieces.append(f'INSERT INTO app.admin_account_role_capabilities(role,permission) VALUES({quote(role)},{quote(permission)});\n')
    for o in objects:
        if o['type'] in ('index', 'view'):
            converted = transform(o['sql'])
            if o['type'] == 'view': converted = re.sub(r'^(CREATE VIEW \w+) AS ',r'\1 WITH (security_invoker=true) AS ',converted)
            pieces.append(converted + ';\n')
    pieces.append('CREATE UNIQUE INDEX admin_users_email_casefold ON app.admin_users(lower(email));\n')
    for o in objects:
        if o['type'] == 'trigger': pieces.append(trigger_sql(o))
    # The deployed baseline keeps its original Storage input. Current Storage
    # corrections belong to additive migrations, never a rewritten baseline.
    pieces.append((HERE / 'baseline-inputs/storage.sql').read_text())
    pieces.append((HERE / 'authority.sql').read_text())
    # Preserve every financial/destination/consent predicate in the original
    # eligibility view. Add only the managed equivalent of its OTP-proof arm.
    sms_view = next(o['sql'] for o in objects if o['type'] == 'view' and o['name'] == 'assisted_sms_current_jobs')
    old_phone_arm = "AND (u.member_type!='app' OR EXISTS(SELECT 1 FROM auth_otp_verifications"
    if sms_view.count(old_phone_arm) != 1: raise ValueError('Review changed assisted SMS phone-proof predicate')
    sms_view = sms_view.replace(old_phone_arm, "AND (u.member_type!='app' OR private.managed_phone_binding(u.id,consent.phone_verification_challenge_id,u.phone) OR EXISTS(SELECT 1 FROM auth_otp_verifications")
    sms_view = transform(sms_view)
    sms_view = re.sub(r'^CREATE VIEW (\w+) AS ', r'CREATE OR REPLACE VIEW app.\1 WITH (security_invoker=true) AS ', sms_view)
    pieces.append(sms_view + ';\n')
    pieces.append((HERE / 'financial.sql').read_text())
    pieces.append((HERE / 'managed-retention.sql').read_text())
    # A schema-local default revoke cannot remove the global default PUBLIC
    # EXECUTE grant. Sweep AFTER every curated function has been created.
    pieces.append('REVOKE ALL ON ALL FUNCTIONS IN SCHEMA app,private,api FROM PUBLIC;\n')
    pieces.append("DO $$DECLARE r text;BEGIN FOREACH r IN ARRAY ARRAY['anon','authenticated','service_role'] LOOP IF EXISTS(SELECT 1 FROM pg_roles WHERE rolname=r) THEN EXECUTE format('REVOKE ALL ON ALL FUNCTIONS IN SCHEMA app,private,api FROM %I',r);END IF;END LOOP;END$$;\n")
    pieces.append('COMMIT;\n')
    output = ''.join(pieces)
    manifest = {'format': 'collect.supabase.baseline.v1', 'source_counts': counts, 'source_migrations': inputs, 'baseline_sha256': hashlib.sha256(output.encode()).hexdigest(), 'source_table_names': [o['name'] for o in objects if o['type'] == 'table'], 'source_trigger_names': [o['name'] for o in objects if o['type'] == 'trigger'], 'translation': 'shape-preserving PostgreSQL17, explicit compatibility functions and curated authority/financial additions', 'semantic_equivalence_accepted': False}
    manifest_body = json.dumps(manifest, indent=2) + '\n'
    if args.check:
        for name, expected in [('baseline.sql', output), ('source_manifest.json', manifest_body)]:
            if not (HERE / name).is_file() or (HERE / name).read_text() != expected:
                raise SystemExit('Generated source drift: ' + name)
    else:
        (HERE / 'baseline.sql').write_text(output)
        (HERE / 'source_manifest.json').write_text(manifest_body)
    print(json.dumps({'checked' if args.check else 'generated': str(HERE / 'baseline.sql'), 'sha256': manifest['baseline_sha256'], **counts}))


if __name__ == '__main__': main()

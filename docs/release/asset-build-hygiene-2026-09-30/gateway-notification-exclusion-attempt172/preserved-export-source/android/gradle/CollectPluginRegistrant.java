import java.io.IOException;
import java.nio.charset.CodingErrorAction;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.HashSet;
import java.util.Set;
import java.util.regex.Matcher;
import java.util.regex.Pattern;

/** Repository adapter of the pinned Flutter registrant, without editing it. */
public final class CollectPluginRegistrant {
    private static final String HEADER = String.join("\n",
        "package io.flutter.plugins;", "", "import androidx.annotation.Keep;",
        "import androidx.annotation.NonNull;", "import io.flutter.Log;", "",
        "import io.flutter.embedding.engine.FlutterEngine;", "", "/**",
        " * Generated file. Do not edit.",
        " * This file is generated by the Flutter tool based on the",
        " * plugins that support the Android platform.", " */", "@Keep",
        "public final class GeneratedPluginRegistrant {",
        "  private static final String TAG = \"GeneratedPluginRegistrant\";",
        "  public static void registerWith(@NonNull FlutterEngine flutterEngine) {", "");
    private static final String FOOTER = "  }\n}\n";
    private static final Pattern BLOCK = Pattern.compile(
        "    try \\{\\n      flutterEngine\\.getPlugins\\(\\)\\.add\\(new "
        + "([A-Za-z_$][\\w$]*(?:\\.[A-Za-z_$][\\w$]*)+)\\(\\)\\);\\n"
        + "    \\} catch \\(Exception e\\) \\{\\n"
        + "      Log\\.e\\(TAG, \"Error registering plugin ([a-z0-9_]+), \\1\", e\\);\\n"
        + "    \\}\\n");
    private static final String NOTIFICATION_NAME = "flutter_local_notifications";
    private static final String NOTIFICATION_CLASS =
        "com.dexterous.flutterlocalnotifications.FlutterLocalNotificationsPlugin";

    static String render(String source, boolean omitNotifications) {
        if (!source.startsWith(HEADER) || !source.endsWith(FOOTER)) {
            throw new IllegalArgumentException("Unknown Flutter registrant envelope");
        }
        String body = source.substring(HEADER.length(), source.length() - FOOTER.length());
        Matcher matcher = BLOCK.matcher(body);
        int cursor = 0;
        int notifications = 0;
        Set<String> names = new HashSet<>();
        Set<String> classes = new HashSet<>();
        StringBuilder result = new StringBuilder(HEADER);
        while (matcher.find()) {
            if (matcher.start() != cursor) {
                throw new IllegalArgumentException("Unknown Flutter registration template");
            }
            String pluginClass = matcher.group(1);
            String pluginName = matcher.group(2);
            if (!names.add(pluginName) || !classes.add(pluginClass)) {
                throw new IllegalArgumentException("Duplicate Flutter registration");
            }
            boolean notification = pluginName.equals(NOTIFICATION_NAME);
            if (notification != pluginClass.equals(NOTIFICATION_CLASS)) {
                throw new IllegalArgumentException("Unknown notification registration identity");
            }
            if (notification) notifications++;
            if (!notification || !omitNotifications) result.append(matcher.group());
            cursor = matcher.end();
        }
        if (cursor != body.length() || notifications != 1) {
            throw new IllegalArgumentException("Incomplete or missing Flutter notification registration");
        }
        result.append(FOOTER);
        return result.toString();
    }

    public static void main(String[] args) throws IOException {
        if (args.length != 3 || !(args[2].equals("true") || args[2].equals("false"))) {
            throw new IllegalArgumentException("Expected input, output and explicit omission Boolean");
        }
        Path input = Path.of(args[0]);
        Path output = Path.of(args[1]);
        if (!Files.isRegularFile(input) || Files.isSymbolicLink(input)) {
            throw new IllegalArgumentException("Missing regular tool-generated registrant");
        }
        byte[] original = Files.readAllBytes(input);
        String source = StandardCharsets.UTF_8.newDecoder()
            .onMalformedInput(CodingErrorAction.REPORT).decode(java.nio.ByteBuffer.wrap(original)).toString();
        byte[] rendered = render(source, Boolean.parseBoolean(args[2])).getBytes(StandardCharsets.UTF_8);
        if (!java.util.Arrays.equals(original, Files.readAllBytes(input))) {
            throw new IllegalArgumentException("Registrant changed during generation");
        }
        Files.createDirectories(output.getParent());
        Files.write(output, rendered);
    }
}
